import type { GameFactory } from "./game";
import type { Pack } from "./types";
import { createGeneratedGame } from "./games/generated";
import { createAim } from "./games/aim";
import { createBoulder } from "./games/boulder";
import { createGradient } from "./games/gradient";
import { createMetronome } from "./games/metronome";
import { createReaction } from "./games/reaction";
import { createSnake } from "./games/snake";
import { createTyping } from "./games/typing";
import { createUntangle } from "./games/untangle";

/**
 * Every game the app knows about. There is no free/paid split: all of these
 * ship to everyone.
 *
 * Adding a game is one new file in src/games/ implementing GameModule, one line
 * here, and one id in src-tauri/src/logic/games.rs. CI fails if those last two
 * drift apart — see scripts/check-game-ids.mjs.
 */
export const REGISTRY: Record<string, GameFactory> = {
  snake: createSnake,
  typing: createTyping,
  aim: createAim,
  reaction: createReaction,
  gradient: createGradient,
  metronome: createMetronome,
  untangle: createUntangle,
  boulder: createBoulder,
};

export const GAME_IDS: readonly string[] = Object.keys(REGISTRY);

/**
 * Games generated by the user's agent, discovered at runtime rather than
 * compiled in. Kept in a second map on purpose: REGISTRY above is parsed as
 * text by scripts/check-game-ids.mjs to prove it matches the Rust list, and
 * merging runtime entries into it would either break that check or make it
 * lie.
 */
const packRegistry: Record<string, GameFactory> = {};

/** Replace the known packs. Called at boot and whenever Rust says they changed. */
export function registerPacks(packs: readonly Pack[]): void {
  for (const id of Object.keys(packRegistry)) delete packRegistry[id];
  for (const pack of packs) packRegistry[pack.id] = createGeneratedGame(pack);
}

/** The factory for `id`, built-in or generated, or undefined if unknown. */
export function getGameFactory(id: string): GameFactory | undefined {
  return REGISTRY[id] ?? packRegistry[id];
}

/**
 * Every playable game id. Built-ins keep their hand-picked order and packs
 * follow, so adding a generated game never reshuffles the tab bar.
 */
export function allGameIds(): readonly string[] {
  return [...GAME_IDS, ...Object.keys(packRegistry)];
}
