import type { GameApi, GameModule } from "../../game";

const START_NODES = 7;
const MAX_NODES = 12;
const NODE_R = 11;

interface Node {
  x: number;
  y: number;
}

type Edge = [number, number];

function segmentsCross(a: Node, b: Node, c: Node, d: Node): boolean {
  // Standard orientation test. Shared endpoints never count as a crossing,
  // which is why edges sharing a node are filtered out before we get here.
  const orient = (p: Node, q: Node, r: Node) =>
    Math.sign((q.y - p.y) * (r.x - q.x) - (q.x - p.x) * (r.y - q.y));
  const o1 = orient(a, b, c);
  const o2 = orient(a, b, d);
  const o3 = orient(c, d, a);
  const o4 = orient(c, d, b);
  if (o1 !== o2 && o3 !== o4) return true;

  // Collinear overlap also counts. Without this, dragging every node onto one
  // straight line reads as "untangled" and trivially wins the board.
  const onSegment = (p: Node, q: Node, r: Node) =>
    Math.min(p.x, r.x) - 0.001 <= q.x &&
    q.x <= Math.max(p.x, r.x) + 0.001 &&
    Math.min(p.y, r.y) - 0.001 <= q.y &&
    q.y <= Math.max(p.y, r.y) + 0.001;
  if (o1 === 0 && onSegment(a, c, b)) return true;
  if (o2 === 0 && onSegment(a, d, b)) return true;
  if (o3 === 0 && onSegment(c, a, d)) return true;
  if (o4 === 0 && onSegment(c, b, d)) return true;
  return false;
}

/**
 * Drag nodes until no edges cross.
 *
 * Generated by placing nodes on a circle and connecting them there, so every
 * board is guaranteed solvable — the untangled solution is the circle we
 * scattered them from.
 *
 * Scored as the best percentage of crossings removed this run: defined at
 * every frame, capped at 100, and immune to run length.
 */
export function createUntangle(): GameModule {
  let api: GameApi;
  let canvas: HTMLCanvasElement;
  let ctx: CanvasRenderingContext2D;
  let meta: HTMLParagraphElement;
  let raf = 0;
  let frozen = false;

  let nodes: Node[] = [];
  let edges: Edge[] = [];
  let startCrossings = 1;
  let dragging: number | null = null;
  let hovered: number | null = null;
  let nodeCount = START_NODES;
  let bestPercent = 0;
  let solved = 0;

  function newBoard(): void {
    const w = canvas.width;
    const h = canvas.height;
    const cx = w / 2;
    const cy = h / 2;
    const ring = Math.min(w, h) / 2 - 40;

    const solution: Node[] = [];
    for (let i = 0; i < nodeCount; i++) {
      const angle = (i / nodeCount) * Math.PI * 2 - Math.PI / 2;
      solution.push({ x: cx + Math.cos(angle) * ring, y: cy + Math.sin(angle) * ring });
    }

    // Connect each node to two others it is not adjacent to on the ring: the
    // ring layout untangles them, but the scattered layout looks like a knot.
    edges = [];
    for (let i = 0; i < nodeCount; i++) {
      for (const step of [2, 3]) {
        const j = (i + step) % nodeCount;
        if (i < j && !edges.some(([a, b]) => a === i && b === j)) edges.push([i, j]);
      }
    }

    do {
      nodes = solution.map(() => ({
        x: 40 + Math.random() * (w - 80),
        y: 40 + Math.random() * (h - 80),
      }));
      startCrossings = countCrossings();
    } while (startCrossings < 3);

    bestPercent = Math.max(bestPercent, 0);
  }

  function countCrossings(): number {
    let count = 0;
    for (let i = 0; i < edges.length; i++) {
      for (let j = i + 1; j < edges.length; j++) {
        const [a, b] = edges[i];
        const [c, d] = edges[j];
        if (a === c || a === d || b === c || b === d) continue;
        if (segmentsCross(nodes[a], nodes[b], nodes[c], nodes[d])) count += 1;
      }
    }
    return count;
  }

  function crossingEdges(): Set<number> {
    const bad = new Set<number>();
    for (let i = 0; i < edges.length; i++) {
      for (let j = i + 1; j < edges.length; j++) {
        const [a, b] = edges[i];
        const [c, d] = edges[j];
        if (a === c || a === d || b === c || b === d) continue;
        if (segmentsCross(nodes[a], nodes[b], nodes[c], nodes[d])) {
          bad.add(i);
          bad.add(j);
        }
      }
    }
    return bad;
  }

  function percentRemoved(current: number): number {
    if (startCrossings === 0) return 100;
    return Math.max(0, ((startCrossings - current) / startCrossings) * 100);
  }

  function toCanvas(event: MouseEvent): Node {
    const rect = canvas.getBoundingClientRect();
    return {
      x: ((event.clientX - rect.left) / rect.width) * canvas.width,
      y: ((event.clientY - rect.top) / rect.height) * canvas.height,
    };
  }

  function nodeAt(point: Node): number | null {
    for (let i = 0; i < nodes.length; i++) {
      const dx = nodes[i].x - point.x;
      const dy = nodes[i].y - point.y;
      if (dx * dx + dy * dy <= (NODE_R + 7) ** 2) return i;
    }
    return null;
  }

  function onDown(event: MouseEvent): void {
    if (frozen) return;
    dragging = nodeAt(toCanvas(event));
  }

  function onMove(event: MouseEvent): void {
    if (frozen) return;
    const point = toCanvas(event);
    hovered = nodeAt(point);
    if (dragging === null) return;

    const pad = NODE_R + 4;
    nodes[dragging] = {
      x: Math.min(canvas.width - pad, Math.max(pad, point.x)),
      y: Math.min(canvas.height - pad, Math.max(pad, point.y)),
    };
  }

  function onUp(): void {
    if (frozen || dragging === null) return;
    dragging = null;

    const current = countCrossings();
    const percent = percentRemoved(current);
    if (percent > bestPercent) {
      bestPercent = percent;
      api.reportScore(bestPercent);
    }
    if (current === 0) {
      solved += 1;
      nodeCount = Math.min(MAX_NODES, nodeCount + 1);
      window.setTimeout(() => {
        if (!frozen) newBoard();
      }, 750);
    }
  }

  function draw(): void {
    ctx.fillStyle = "#12141a";
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    const bad = crossingEdges();
    for (let i = 0; i < edges.length; i++) {
      const [a, b] = edges[i];
      ctx.strokeStyle = bad.has(i) ? "rgba(224, 112, 74, 0.85)" : "rgba(127, 214, 164, 0.55)";
      ctx.lineWidth = bad.has(i) ? 2 : 1.5;
      ctx.beginPath();
      ctx.moveTo(nodes[a].x, nodes[a].y);
      ctx.lineTo(nodes[b].x, nodes[b].y);
      ctx.stroke();
    }

    for (let i = 0; i < nodes.length; i++) {
      const active = i === dragging || i === hovered;
      ctx.fillStyle = active ? "#7fd6a4" : "#cfd4dd";
      ctx.beginPath();
      ctx.arc(nodes[i].x, nodes[i].y, active ? NODE_R + 2 : NODE_R, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = "#12141a";
      ctx.beginPath();
      ctx.arc(nodes[i].x, nodes[i].y, 3.5, 0, Math.PI * 2);
      ctx.fill();
    }

    const current = countCrossings();
    const parts = [
      current === 0 ? "untangled" : `${current} crossing${current === 1 ? "" : "s"}`,
      `${Math.round(percentRemoved(current))}%`,
    ];
    if (solved > 0) parts.push(`${solved} solved`);
    meta.textContent = parts.join(" · ");
  }

  function loop(): void {
    raf = requestAnimationFrame(loop);
    if (!frozen) draw();
  }

  return {
    id: "untangle",
    label: "Untangle",
    unit: "%",
    lowerIsBetter: false,

    mount(root: HTMLElement, gameApi: GameApi): void {
      api = gameApi;
      const wrap = document.createElement("div");
      wrap.className = "untangle";
      canvas = document.createElement("canvas");
      canvas.width = 470;
      canvas.height = 400;
      canvas.className = "board untangle-board";
      meta = document.createElement("p");
      meta.className = "untangle-meta";
      wrap.append(canvas, meta);
      root.appendChild(wrap);
      ctx = canvas.getContext("2d")!;

      newBoard();
      canvas.addEventListener("mousedown", onDown);
      window.addEventListener("mousemove", onMove);
      window.addEventListener("mouseup", onUp);
      raf = requestAnimationFrame(loop);
    },

    freeze(): void {
      frozen = true;
      // Credit progress made in a drag that was still in flight.
      const percent = percentRemoved(countCrossings());
      if (percent > bestPercent) {
        bestPercent = percent;
        api.reportScore(bestPercent);
      }
      draw();
    },

    destroy(): void {
      frozen = true;
      cancelAnimationFrame(raf);
      canvas?.removeEventListener("mousedown", onDown);
      window.removeEventListener("mousemove", onMove);
      window.removeEventListener("mouseup", onUp);
      canvas?.parentElement?.remove();
    },
  };
}
